# (rounded first, so that a small negative value prints as 0.000, not -0.000)
f3 <- function(x) if (is.na(x)) "--" else formatC(round(x, 3) + 0, format = "f", digits = 3)
pct <- function(x) if (is.na(x)) "--" else formatC(round(100 * x, 1) + 0, format = "f", digits = 1)
cells <- list() # every printed number: exhibit, source key, column, value, printed text
rec <- function(exhibit, key, column, value, printed) {
  cells[[length(cells) + 1]] <<- data.frame(exhibit = exhibit, source = key$source %||% "summary", design = key$design %||% NA,
    estimator = key$estimator %||% NA, model = key$model %||% NA, parameter = key$parameter %||% NA, H = key$H %||% NA,
    row = key$row %||% NA, column = column, value = value, printed = printed, stringsAsFactors = FALSE)
  printed
}
`%||%` <- function(a, b) if (is.null(a)) b else a
# one summary row by key (stops if not exactly one)
srow <- function(design, estimator, model, parameter, H) {
  r <- s[s$design == design & s$estimator == estimator & s$model == model & s$parameter == parameter & s$H == H, ]
  if (nrow(r) != 1) stop("summary rows for ", paste(design, estimator, model, parameter, H), ": ", nrow(r))
  r
}
# printed cell from a summary column, recorded
cell <- function(exhibit, r, column, fmt = f3, wrap = function(x) x) {
  v <- r[[column]]
  rec(exhibit, list(design = r$design, estimator = r$estimator, model = r$model, parameter = r$parameter, H = r$H), column, v, wrap(fmt(v)))
}
write.table.tex <- function(file, body, prov = provenance) {
  writeLines(c(prov, "", body), file.path(out.dir, file))
  message("wrote ", file.path(out.dir, file))
}
mcse.range <- function(x) sprintf("%s--%s", f3(min(x)), f3(max(x)))

