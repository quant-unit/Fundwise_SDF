# Fund-size imputation sensitivity for FW estimation (Phase 1.1 deliverable).
# Compares three rules on North America Buyout and VC (V <= 2010):
#   1. Within-vintage median with nearby-vintage fallback (new baseline, data_prepared_2026_c)
#   2. Pooled cross-vintage mean (legacy rule, data_prepared_2026_c_fwmean)
#   3. Dropping missing-size funds (data_prepared_2026_c_fwdrop)
# Reports explicit fund counts, vintage counts (L2 vs U_{v,H}), matched-vintage
# L2, L2 - U_{v,H} gaps, 0->30 yr L2 declines, and joint (alpha, beta) at H = 0, 15.
# Run from r_project/:  LANG=en_US.UTF-8 Rscript results/fw_imputation_sensitivity.R
source("simulation/mc_driver.R")
out.dir <- "results/figures_bovc_us_g1"
dir.create(out.dir, showWarnings = FALSE, recursive = TRUE)

pub <- mc.public.factors()
fc <- unique(c("RF", setdiff(colnames(pub), "Date")))

RULES <- list(
  median = list(label = "Within-vintage median (baseline)", dir = "empirical/data_prepared_2026_c"),
  mean   = list(label = "Pooled cross-vintage mean",        dir = "empirical/data_prepared_2026_c_fwmean"),
  drop   = list(label = "Drop missing-size funds",          dir = "empirical/data_prepared_2026_c_fwdrop")
)

load.fw <- function(dir, vyp, type) {
  d <- read.csv(file.path(dir, sprintf("preqin_cashflows_FW%s_North America_NAV.csv", if (vyp) "_VYP" else "")), stringsAsFactors = FALSE)
  d$Date <- as.Date(d$Date)
  d$Fund.ID <- as.factor(paste(d$Fund.ID, d$type, sep = "_"))
  d <- pad.all.units(d, "first.cf", max(d$Date))
  d <- merge(d, pub, by = "Date", all.x = TRUE)
  d <- d[d$type == type & d$Vintage <= 2010, ]
  d$Fund.ID <- droplevels(as.factor(as.character(d$Fund.ID)))
  prepare.fast(d, fc)
}

rows <- list()
for (ty in c("BO", "VC")) {
  for (rk in names(RULES)) {
    dir <- RULES[[rk]]$dir
    fv <- load.fw(dir, TRUE, ty)
    ff <- load.fw(dir, FALSE, ty)
    v.cnt <- table(ff$vintage)
    elig.v <- sort(as.integer(names(v.cnt)[v.cnt >= 2L]))
    fvm <- fast.subset(fv, fv$vintage %in% elig.v)
    n.funds <- ff$n.units
    V.l2 <- fv$n.units
    V.u <- length(elig.v)

    # Single-factor MKT at H = 0, 5, 15, 30 yr
    for (m in c(0, 60, 180, 360)) {
      r.l2 <- mc.fit(MC.ESTIMATORS$L2.vyp, fv, "MKT", m)
      r.l2m <- mc.fit(MC.ESTIMATORS$L2.vyp, fvm, "MKT", m)
      r.u <- mc.fit(MC.ESTIMATORS$U.eq.fw, ff, "MKT", m)
      rows[[length(rows) + 1L]] <- data.frame(
        type = ty, rule = rk, label = RULES[[rk]]$label, model = "MKT", max.month = m, H = m / 12,
        n.funds = n.funds, V.l2 = V.l2, V.u = V.u,
        l2.beta = r.l2$MKT, l2.se = r.l2$SE.MKT, l2.bound = r.l2$at.bound,
        l2m.beta = r.l2m$MKT, l2m.se = r.l2m$SE.MKT,
        u.beta = r.u$MKT, u.se = r.u$SE.MKT, u.bound = r.u$at.bound,
        gap.l2u = r.l2$MKT - r.u$MKT, gap.l2mu = r.l2m$MKT - r.u$MKT,
        l2.alpha = NA_real_, u.alpha = NA_real_, stringsAsFactors = FALSE
      )
    }
    # Joint (alpha, beta) at H = 0 and 15 yr
    for (m in c(0, 180)) {
      r.l2 <- mc.fit(MC.ESTIMATORS$L2.vyp, fv, "Alpha", m)
      r.u <- mc.fit(MC.ESTIMATORS$U.eq.fw, ff, "Alpha", m)
      rows[[length(rows) + 1L]] <- data.frame(
        type = ty, rule = rk, label = RULES[[rk]]$label, model = "Alpha", max.month = m, H = m / 12,
        n.funds = n.funds, V.l2 = V.l2, V.u = V.u,
        l2.beta = r.l2$MKT, l2.se = r.l2$SE.MKT, l2.bound = r.l2$at.bound,
        l2m.beta = NA_real_, l2m.se = NA_real_,
        u.beta = r.u$MKT, u.se = r.u$SE.MKT, u.bound = r.u$at.bound,
        gap.l2u = r.l2$MKT - r.u$MKT, gap.l2mu = NA_real_,
        l2.alpha = 100 * r.l2$Coef, u.alpha = 100 * r.u$Coef, stringsAsFactors = FALSE
      )
    }
  }
}
df <- do.call(rbind, rows)
write.csv(df, file.path(out.dir, "fw_imputation_sensitivity.csv"), row.names = FALSE)

f3 <- function(x) if (is.na(x)) "--" else formatC(round(x, 3) + 0, format = "f", digits = 3)
lines <- character(0)
for (ty in c("BO", "VC")) {
  lines <- c(lines, sprintf("\\multicolumn{11}{l}{\\textit{%s, fund-size weighted (FW)}} \\\\",
    c(BO = "Buyout", VC = "Venture capital")[[ty]]))
  for (rk in names(RULES)) {
    sub <- df[df$type == ty & df$rule == rk & df$model == "MKT", ]
    r0 <- sub[sub$H == 0, ]; r15 <- sub[sub$H == 15, ]; r30 <- sub[sub$H == 30, ]
    decl <- r0$l2.beta - r30$l2.beta
    lines <- c(lines, sprintf("\\quad %s & %d & %d/%d & %s & %s & %s & %s & %s & %s & %s & %s \\\\",
      RULES[[rk]]$label, r0$n.funds, r0$V.l2, r0$V.u,
      f3(r0$u.beta), f3(r15$u.beta), f3(r30$u.beta),
      f3(r0$l2.beta), f3(r15$l2.beta), f3(r30$l2.beta),
      f3(decl),
      if (r0$V.l2 == r0$V.u) f3(r0$gap.l2u) else sprintf("%s [%s]", f3(r0$gap.l2u), f3(r0$gap.l2mu))))
  }
  if (ty == "BO") lines <- c(lines, "\\addlinespace")
}
