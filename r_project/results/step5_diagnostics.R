for (i in seq_len(nrow(cells))) {
  ty <- cells$type[i]; w <- cells$w[i]; k <- paste(ty, w)
  fv <- DATA[[k]]$vyp$fp; ff <- DATA[[k]]$fund$fp
  u0 <- mc.fit(est.U(w), ff, "MKT", 0)
  b0 <- u0$MKT
  pv.pool <- fast.unit.errors(c(MKT = b0), fv, 0)
  pv.fund <- fast.unit.errors(c(MKT = b0), ff, 0)
  # Fund-level NPV per unit commitment (for FW, divide by fund size)
  pv.unit <- if (w == "FW") pv.fund / ff$size else pv.fund
  wts <- if (w == "FW") ff$size else rep(1, ff$n.units)
  for (j in seq_along(fv$vintage)) {
    v <- fv$vintage[j]
    idx <- which(ff$vintage == v)
    nv <- length(idx)
    wi <- wts[idx] / sum(wts[idx])
    mu <- sum(wi * pv.unit[idx])
    # Within-vintage SE of the weighted mean: sqrt(sum(wi^2) * s_w^2) when nv >= 2
    se.w <- if (nv >= 2L) {
      # Unbiased weighted variance estimator (reliability weights)
      denom <- 1 - sum(wi^2)
      if (denom > 0) sqrt(sum(wi^2) * sum(wi * (pv.unit[idx] - mu)^2) / denom) else NA_real_
    } else NA_real_
    pv.rows[[length(pv.rows) + 1L]] <- data.frame(
      type = ty, weighting = w, Vintage = v, n.funds = nv, beta.u0 = b0,
      pv.pool = unname(pv.pool[j]), pv.check = mu, se.within = se.w,
      stringsAsFactors = FALSE
    )
  }
}
