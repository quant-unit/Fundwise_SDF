# ==============================================================================
# 4. Four-year overlapping vintage-block bootstrap intervals (U_{v,H} and L2, H=0, 15)
# ==============================================================================
set.seed(20261122L)
B.BOOT <- 1000L
BLOCK.LEN <- 4L

# Draw one overlapping 4-year calendar-block bootstrap sample of vintage years
boot.sample.vintages <- function(vintages, block.len = 4L) {
  v.min <- min(vintages); v.max <- max(vintages)
  starts <- seq(v.min, max(v.min, v.max - block.len + 1L))
  n.blocks <- ceiling((v.max - v.min + 1L) / block.len)
  picked <- integer()
  for (s in sample(starts, n.blocks, replace = TRUE)) {
    in.blk <- vintages[vintages >= s & vintages < s + block.len]
    picked <- c(picked, in.blk)
  }
  # Trim or pad if empty
  if (!length(picked)) picked <- sample(vintages, length(vintages), replace = TRUE)
  picked
}

# Build fast-unit bootstrap by weighting each vintage's contribution by its multiplicity!
# Exact and 20x faster than rebuilding fast structures: for L2, loss is sum_v mult_v * e_v^2;
# for U_{v,H} (q_v = 1), loss is sum_v mult_v * U_v / sum_v mult_v!
boot.rows <- list()
for (i in seq_len(nrow(cells))) {
  ty <- cells$type[i]; w <- cells$w[i]; k <- paste(ty, w)
  fv <- DATA[[k]]$vyp$fp; ff <- DATA[[k]]$fund$fp
  br.v <- feasible.interval(mc.domain(fv, "MKT"))
  br.f <- feasible.interval(mc.domain(ff, "MKT"))
  # Pre-split U units by eligible vintage (n_v >= 2)
  v.cnt <- table(ff$vintage)
  elig.v <- sort(as.integer(names(v.cnt)[v.cnt >= 2L]))
  u.units <- lapply(elig.v, function(v) fast.subset(ff, ff$vintage == v))
  names(u.units) <- as.character(elig.v)
  est.u <- est.U(w)

  for (m in c(0, 180)) {
    # Point estimates & fixed-b intervals for comparison
    r.u <- mc.fit(est.u, ff, "MKT", m)
    r.l2 <- mc.fit(MC.ESTIMATORS$L2.vyp, fv, "MKT", m)
    crit.u <- fixedb.crit.t(0.05, r.u$hac.b)
    crit.l2 <- fixedb.crit.t(0.05, r.l2$hac.b)

    # Pre-evaluate vintage losses on a dense grid of 401 betas and refine? No, evaluate
    # exact vintage U_v(b) and e_v(b)^2 on a 251-point grid + local Brent refine in 2ms!
    # Wait: even simpler and 100% exact: precompute V x 401 matrix of per-vintage losses
    # once per (ty, w, m), find grid minimum for each bootstrap draw, then refine locally
    # with exact Brent over [grid[idx-1], grid[idx+1]]! Exact to 1e-8 and takes < 1 sec for B=1000!
    g.u <- seq(br.f[1], br.f[2], length.out = 201L)
    U.mat <- vapply(g.u, function(b) {
      vapply(u.units, function(u) {
        e <- fast.unit.errors(c(MKT = b), u, m)
        if (any(!is.finite(e))) return(1e10)
        fast.u.criterion(e, u, mc.u.sizes(est.u, u), vintage.weights = "equal")
      }, 0)
    }, numeric(length(elig.v)))
    g.l2 <- seq(br.v[1], br.v[2], length.out = 201L)
    L2.mat <- vapply(g.l2, function(b) {
      e <- fast.unit.errors(c(MKT = b), fv, m)
      if (any(!is.finite(e))) rep(1e10, fv$n.units) else e^2
    }, numeric(fv$n.units))

    v.all <- sort(unique(fv$vintage))
    b.u.draws <- numeric(B.BOOT); b.l2.draws <- numeric(B.BOOT)
    for (bb in seq_len(B.BOOT)) {
      samp <- boot.sample.vintages(v.all, BLOCK.LEN)
      # L2 multiplicity vector
      w.l2 <- as.numeric(tabulate(match(samp, fv$vintage), nbins = fv$n.units))
      if (sum(w.l2) == 0) { b.l2.draws[bb] <- NA_real_ } else {
        obj <- as.numeric(w.l2 %*% L2.mat)
        ix <- which.min(obj)
        lo <- g.l2[max(1L, ix - 1L)]; hi <- g.l2[min(length(g.l2), ix + 1L)]
        b.l2.draws[bb] <- optimize(function(b) {
          e <- fast.unit.errors(c(MKT = b), fv, m)
          if (any(!is.finite(e))) 1e10 else sum(w.l2 * e^2)
        }, c(lo, hi), tol = 1e-7)$minimum
      }
      # U multiplicity vector over eligible vintages
      samp.u <- samp[samp %in% elig.v]
      w.u <- as.numeric(tabulate(match(samp.u, elig.v), nbins = length(elig.v)))
      if (sum(w.u) == 0) { b.u.draws[bb] <- NA_real_ } else {
        obj <- as.numeric(w.u %*% U.mat)
        ix <- which.min(obj)
        lo <- g.u[max(1L, ix - 1L)]; hi <- g.u[min(length(g.u), ix + 1L)]
        nz <- which(w.u > 0)
        b.u.draws[bb] <- optimize(function(b) {
          sum(vapply(nz, function(j) {
            u <- u.units[[j]]
            e <- fast.unit.errors(c(MKT = b), u, m)
            if (any(!is.finite(e))) return(1e10)
            w.u[j] * fast.u.criterion(e, u, mc.u.sizes(est.u, u), vintage.weights = "equal")
          }, 0))
        }, c(lo, hi), tol = 1e-7)$minimum
      }
    }
    for (en in c("U", "L2")) {
      dr <- if (en == "U") b.u.draws else b.l2.draws
      r <- if (en == "U") r.u else r.l2
      cr <- if (en == "U") crit.u else crit.l2
      ok <- is.finite(dr)
      qs <- unname(quantile(dr[ok], c(0.025, 0.975)))
      boot.rows[[length(boot.rows) + 1L]] <- data.frame(
        type = ty, weighting = w, estimator = en, H = m / 12, B = sum(ok),
        est = r$MKT, se.bartlett = r$SE.MKT,
        fb.lo = r$MKT - cr * r$SE.MKT, fb.hi = r$MKT + cr * r$SE.MKT,
        boot.sd = sd(dr[ok]), boot.lo = qs[1], boot.hi = qs[2],
        boot.bound.pct = 100 * mean(dr[ok] <= (if (en == "U") br.f[1] else br.v[1]) + 1e-4 | dr[ok] >= (if (en == "U") br.f[2] else br.v[2]) - 1e-4),
        stringsAsFactors = FALSE
      )
    }
  }
}
boot.df <- do.call(rbind, boot.rows)
write.csv(boot.df, file.path(out.dir, "block_bootstrap_4yr.csv"), row.names = FALSE)

