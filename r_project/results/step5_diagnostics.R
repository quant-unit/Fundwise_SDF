# Merton (1980) benchmark on historical 1985-2021 monthly market excess returns
mkt.sub <- pub[pub$Date >= as.Date("1985-01-31") & pub$Date <= as.Date("2021-12-31"), ]
sigma.mkt.m <- sd(mkt.sub$MKT) # monthly SD
T.years <- nrow(mkt.sub) / 12
merton.se.annual.1x <- sigma.mkt.m * sqrt(12) / sqrt(T.years) # ~0.155 / sqrt(37) = 2.55%/yr
merton.se.monthly.1x <- merton.se.annual.1x / 12

for (i in seq_len(nrow(cells))) {
  ty <- cells$type[i]; w <- cells$w[i]; k <- paste(ty, w)
  fv <- DATA[[k]]$vyp$fp; ff <- DATA[[k]]$fund$fp
  d <- 1e-4
  # NPV-gradient collinearity across vintages at (beta = 1, alpha = 0)
  pv.a.p <- fast.unit.errors(c(MKT = 1, Alpha = d), fv, 0)
  pv.a.m <- fast.unit.errors(c(MKT = 1, Alpha = -d), fv, 0)
  pv.b.p <- fast.unit.errors(c(MKT = 1 + d, Alpha = 0), fv, 0)
  pv.b.m <- fast.unit.errors(c(MKT = 1 - d, Alpha = 0), fv, 0)
  dPV.da <- (pv.a.p - pv.a.m) / (2 * d)
  dPV.db <- (pv.b.p - pv.b.m) / (2 * d)
  grad.collin <- cor(dPV.da, dPV.db)

  # Hessian of Q_0(alpha, beta) = mean(PV_v^2) at (beta = 1, alpha = 0)
  q0 <- function(b, a) mean(fast.unit.errors(c(MKT = b, Alpha = a), fv, 0)^2)
  H.bb <- (q0(1 + d, 0) - 2 * q0(1, 0) + q0(1 - d, 0)) / d^2
  H.aa <- (q0(1, d) - 2 * q0(1, 0) + q0(1, -d)) / d^2
  H.ab <- (q0(1 + d, d) - q0(1 + d, -d) - q0(1 - d, d) + q0(1 - d, -d)) / (4 * d^2)
  hess.corr <- H.ab / sqrt(H.bb * H.aa)

  for (m in c(0, 180)) {
    r.u <- mc.fit(est.U(w), ff, "Alpha", m)
    r.l2 <- mc.fit(MC.ESTIMATORS$L2.vyp, fv, "Alpha", m)
    corr.u <- if (!isTRUE(r.u$at.bound) && is.finite(r.u$cov.MKT.Coef)) r.u$cov.MKT.Coef / (r.u$SE.MKT * r.u$SE.Coef) else NA_real_
    corr.l2 <- if (!isTRUE(r.l2$at.bound) && is.finite(r.l2$cov.MKT.Coef)) r.l2$cov.MKT.Coef / (r.l2$SE.MKT * r.l2$SE.Coef) else NA_real_
    id.rows[[length(id.rows) + 1L]] <- data.frame(
      type = ty, weighting = w, H = m / 12,
      grad.collin.at.1.0 = grad.collin,
      H.ab.Q0 = H.ab, H.corr.Q0 = hess.corr,
      U.beta = r.u$MKT, U.alpha.pct = 100 * r.u$Coef, U.bound = r.u$at.bound, U.samp.corr = corr.u,
      L2.beta = r.l2$MKT, L2.alpha.pct = 100 * r.l2$Coef, L2.bound = r.l2$at.bound, L2.samp.corr = corr.l2,
      merton.se.monthly.pct = 100 * merton.se.monthly.1x,
      merton.se.annual.pct = 100 * merton.se.annual.1x,
      stringsAsFactors = FALSE
    )
  }
}
