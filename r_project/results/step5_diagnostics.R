# 2. Fix-A vs Scale-Jacobian decomposition (T4)
# ==============================================================================
H.DEC <- c(0, 60, 120, 180, 240, 360)
dec.rows <- list()
for (i in seq_len(nrow(cells))) {
  ty <- cells$type[i]; w <- cells$w[i]; k <- paste(ty, w)
  fv <- DATA[[k]]$vyp$fp; ff <- DATA[[k]]$fund$fp
  br <- feasible.interval(mc.domain(fv, "MKT"))
  b.ref <- mc.fit(est.U(w), ff, "MKT", 0)$MKT
  d <- 1e-4
  for (m in H.DEC) {
    # Full L2 fit at horizon m
    b.l2 <- mc.fit(MC.ESTIMATORS$L2.vyp, fv, "MKT", m)$MKT
    # Fix-A counterfactual: hold A_{v,H} fixed at b.ref, minimize mean( (A_ref * PV_v(b))^2 )
    A.ref <- fast.horizon.scale(c(MKT = b.ref), fv, m)
    f.fixA <- function(b) {
      pv <- fast.unit.errors(c(MKT = b), fv, 0)
      if (any(!is.finite(pv))) return(1e10)
      mean((A.ref * pv)^2)
    }
    b.fixA <- optimize(f.fixA, br, tol = 1e-10)$minimum
    # Exact FOC decomposition of Q_H(b) = mean((A_{v,H}(b) PV_v(b))^2) at b = b.ref
    pv0 <- fast.unit.errors(c(MKT = b.ref), fv, 0)
    dpv <- (fast.unit.errors(c(MKT = b.ref + d), fv, 0) - fast.unit.errors(c(MKT = b.ref - d), fv, 0)) / (2 * d)
    A0 <- fast.horizon.scale(c(MKT = b.ref), fv, m)
    dA <- (fast.horizon.scale(c(MKT = b.ref + d), fv, m) - fast.horizon.scale(c(MKT = b.ref - d), fv, m)) / (2 * d)
    term.disc <- 2 * mean(A0^2 * pv0 * dpv)      # Term (I): Inception Discounting
    term.jac  <- 2 * mean(A0 * dA * pv0^2)       # Term (II): Scale-Jacobian Penalty
    tot.num   <- (mean(fast.unit.errors(c(MKT = b.ref + d), fv, m)^2) - mean(fast.unit.errors(c(MKT = b.ref - d), fv, m)^2)) / (2 * d)
    stopifnot(abs((term.disc + term.jac) - tot.num) < 1e-6 * max(1, abs(tot.num)))
    dec.rows[[length(dec.rows) + 1L]] <- data.frame(
      type = ty, weighting = w, max.month = m, H = m / 12, beta.ref = b.ref,
      beta.l2 = b.l2, beta.fixA = b.fixA, shift.reweight = b.fixA - b.l2[1],
      shift.jacobian = b.l2 - b.fixA,
      slope.disc = term.disc, slope.jac = term.jac, slope.total = term.disc + term.jac,
      stringsAsFactors = FALSE
    )
  }
}
dec.df <- do.call(rbind, dec.rows)
