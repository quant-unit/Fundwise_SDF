# Appendix E: hv-block cross-validation fold diagnostics (B7/B8).
# Summarizes fold stability (SD_CV, SR_CV = full-sample estimate / SD_CV),
# boundary fold counts, horizon-specific validation loss, and common H = 0
# held-out validation loss (validation.error.H0) across horizons for North America
# Buyout and VC (EW and FW).
# Run from r_project/:  LANG=en_US.UTF-8 Rscript results/appendix_e_cv_folds.R
source("helper/result_cache.R")
out.dir <- "results/figures_bovc_us_g1/step5"
dir.create(out.dir, showWarnings = FALSE, recursive = TRUE)

H.SHOW <- c(0, 60, 120, 180, 240, 360)
GIT.STATE <- sprintf("%s%s", system("git rev-parse --short HEAD", intern = TRUE),
  if (length(system("git status --porcelain --untracked-files=no", intern = TRUE))) " (uncommitted changes)" else "")
f3 <- function(x) if (is.na(x)) "--" else formatC(round(x, 3) + 0, format = "f", digits = 3)
f2 <- function(x) if (is.na(x)) "--" else formatC(round(x, 2) + 0, format = "f", digits = 2)

rows <- list()
for (w in c("EW", "FW")) {
  cache <- file.path("results/data_out_2026-emp-c", sprintf("cache_q_factors_preqin_%s_VYP_North America", w))
  d <- read.result.cache(cache, verbose = FALSE)
  d <- d[d$Type %in% c("BO", "VC") & d$Factor %in% c("MKT", "Alpha") & d$max.month %in% H.SHOW, , drop = FALSE]
  for (ty in c("BO", "VC")) for (fac in c("MKT", "Alpha")) for (m in H.SHOW) {
    sub <- d[d$Type == ty & d$Factor == fac & d$max.month == m, , drop = FALSE]
    all.r <- sub[sub$CV.key == "ALL", , drop = FALSE]
    folds <- sub[sub$CV.key != "ALL", , drop = FALSE]
    if (!nrow(all.r) || !nrow(folds)) next
    # Keep latest full-sample row if multiple scenarios wrote ALL
    all.r <- all.r[nrow(all.r), , drop = FALSE]
    sd.b <- sd(folds$MKT, na.rm = TRUE)
    sr.b <- if (is.finite(sd.b) && sd.b > 0) all.r$MKT / sd.b else NA_real_
    rows[[length(rows) + 1L]] <- data.frame(
      type = ty, weighting = w, model = fac, max.month = m, H = m / 12,
      n.folds = nrow(folds), boundary.folds = sum(isTRUE(folds$at.bound) | folds$at.bound %in% TRUE, na.rm = TRUE),
      full.beta = all.r$MKT, fold.mean.beta = mean(folds$MKT, na.rm = TRUE),
      fold.sd.beta = sd.b, sr.cv.beta = sr.b,
      val.err.H = mean(folds$validation.error, na.rm = TRUE),
      val.err.H0 = mean(folds$validation.error.H0, na.rm = TRUE),
      stringsAsFactors = FALSE
    )
  }
}
cv.df <- do.call(rbind, rows)
write.csv(cv.df, file.path(out.dir, "appendix_e_cv_folds.csv"), row.names = FALSE)

lines <- character(0)
for (ty in c("BO", "VC")) for (w in c("EW", "FW")) {
  lines <- c(lines, sprintf("\\multicolumn{8}{l}{\\textit{%s, %s (single-factor MKT, %d folds)}} \\\\",
    c(BO = "Buyout", VC = "Venture capital")[[ty]], c(EW = "equally weighted", FW = "fund-size weighted")[[w]],
    cv.df$n.folds[cv.df$type == ty & cv.df$weighting == w & cv.df$model == "MKT"][1]))
  sub <- cv.df[cv.df$type == ty & cv.df$weighting == w & cv.df$model == "MKT", ]
  for (j in seq_len(nrow(sub))) {
    r <- sub[j, ]
    lines <- c(lines, sprintf("\\quad %s yr & %s & %s & %s & %s & %d & %s & %s \\\\",
      format(r$H), f3(r$full.beta), f3(r$fold.mean.beta), f3(r$fold.sd.beta), f2(r$sr.cv.beta),
      r$boundary.folds, f3(r$val.err.H), f3(r$val.err.H0)))
  }
  if (!(ty == "VC" && w == "FW")) lines <- c(lines, "\\addlinespace")
}
writeLines(c(
  sprintf("%% Auto-generated by r_project/results/appendix_e_cv_folds.R at commit %s", GIT.STATE), "",
  "\\begin{table}[htbp]", "\\centering", "\\footnotesize",
  "\\caption{Cross-validation fold diagnostics ($hv$-block CV): fold stability and common $H=0$ held-out loss (B7/B8)}",
  "\\label{tab:appendix_e_cv_folds}",
  "\\begin{tabular}{l rrrr r rr}", "\\toprule",
  "Horizon & Full $\\hat\\beta$ & Fold mean & $\\mathrm{SD}_{CV}$ & $\\mathrm{SR}_{CV}$ & Bound folds & Val.\\ loss ($H$) & Val.\\ loss ($H=0$) \\\\", "\\midrule",
  lines, "\\bottomrule", "\\end{tabular}", "\\par\\vspace{2pt}",
  "{\\scriptsize\\textit{Notes:} North America complete-history sample ($V\\le 2010$), L2 on constant-composition vintage portfolios. Eight 3-year $hv$-block folds (validation windows 1988--1990 through 2009--2010, buffered by 3-year blocks on each side). $\\mathrm{SD}_{CV}$ is the cross-fold standard deviation (descriptive stability diagnostic, not a sampling SE); $\\mathrm{SR}_{CV}=\\hat\\beta_{\\mathrm{full}}/\\mathrm{SD}_{CV}$ (B7). Val.\\ loss ($H$) averages held-out horizon-$H$ loss; Val.\\ loss ($H=0$) evaluates every horizon's fold estimates on the common $H=0$ held-out loss so horizons are directly comparable (B8). Joint $(\\alpha,\\beta)$ fold diagnostics are stored in \\texttt{appendix\\_e\\_cv\\_folds.csv}.}",
  "\\end{table}"), file.path(out.dir, "table_appendix_e_cv_folds.tex"))
cat("wrote Appendix E CV fold diagnostics table & CSV\n")
