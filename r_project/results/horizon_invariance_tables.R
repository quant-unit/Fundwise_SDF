# Online Supplement table of the specification tests of the U_{v,H} identifying conditions
# (helper/horizon_invariance.R): Panel A, horizon-invariance test on the Preqin panels;
# Panel B, two-moment shared-shock test at H = 0; Panel C, Monte Carlo size and power.
# Inputs: results/figures_bovc_us_g1/horizon_invariance_test.csv and two_moment_test.csv
# (results/horizon_invariance_test.R, licensed data) and results/mc_step4/horizon_invariance_mc.csv
# (simulation/mc_horizon_invariance.R). Writes
# results/figures_bovc_us_g1/table_OA_horizon_invariance.tex and the printed numbers to
# results/figures_bovc_us_g1/horizon_invariance_exhibit_data.csv.
# Run from r_project/:  LANG=en_US.UTF-8 Rscript results/horizon_invariance_tables.R
hi <- read.csv("results/figures_bovc_us_g1/horizon_invariance_test.csv", stringsAsFactors = FALSE)
tm <- read.csv("results/figures_bovc_us_g1/two_moment_test.csv", stringsAsFactors = FALSE)
mc <- read.csv("results/mc_step4/horizon_invariance_mc.csv", stringsAsFactors = FALSE)
f3 <- function(x) formatC(round(x, 3) + 0, format = "f", digits = 3)
f2 <- function(x) formatC(round(x, 2) + 0, format = "f", digits = 2)
pct <- function(x) formatC(round(100 * x, 1) + 0, format = "f", digits = 1)
cells <- list()
rec <- function(panel, key, column, value, printed) {
  cells[[length(cells) + 1]] <<- data.frame(panel = panel, key = key, column = column, value = value, printed = printed, stringsAsFactors = FALSE)
  printed
}
TYPE <- c(BO = "Buyout", VC = "VC")

# Panel A: horizon-invariance test, H1 = 12.5 and 15 yr
pa <- character(0)
for (ty in c("BO", "VC")) for (w in c("EW", "FW")) for (H in c(12.5, 15)) {
  r <- hi[hi$type == ty & hi$weighting == w & hi$H == H, ]
  stopifnot(nrow(r) == 1, !r$bound)
  k <- paste(ty, w, H)
  pa <- c(pa, sprintf("%s & %s & %s & %s & %s & %s & %s & %s & %s & %s \\\\",
    if (w == "EW" && H == 12.5) TYPE[[ty]] else "", if (H == 12.5) w else "", format(H),
    rec("A", k, "beta0", r$beta0, f3(r$beta0)), rec("A", k, "beta1", r$beta1, f3(r$beta1)),
    rec("A", k, "diff", r$diff, f3(r$diff)), rec("A", k, "se.diff", r$se.diff, f3(r$se.diff)),
    rec("A", k, "corr", r$corr, f2(r$corr)), rec("A", k, "t", r$t, f2(r$t)), rec("A", k, "p", r$p, f3(r$p))))
}
# Panel B: two-moment test at H = 0
pb <- character(0)
for (ty in c("BO", "VC")) for (w in c("EW", "FW")) {
  r <- tm[tm$type == ty & tm$weighting == w, ]
  stopifnot(nrow(r) == 1)
  k <- paste(ty, w)
  pb <- c(pb, sprintf("%s & %s & %d & %s & %s & \\multicolumn{2}{c}{[%s, %s]} & %s & & \\\\", if (w == "EW") TYPE[[ty]] else "", w, r$V,
    rec("B", k, "p.max", r$p.max, f3(r$p.max)), rec("B", k, "beta.at.p.max", r$beta.at.p.max, f3(r$beta.at.p.max)),
    rec("B", k, "set.lo", r$set.lo, f2(r$set.lo)), rec("B", k, "set.hi", r$set.hi, f2(r$set.hi)),
    rec("B", k, "set.share", r$set.share, pct(r$set.share))))
}
# Panel C: Monte Carlo size and power
DES <- list(
  core_BO = "Buyout core, EW ($c_v=0$)", core_VC = "VC core, EW ($c_v=0$)",
  s_core_BO = "Buyout, fund sizes, FW ($c_v=0$)", s_core_VC = "VC, fund sizes, FW ($c_v=0$)",
  m4_shared = "Buyout, shared shock $c$ ($\\sigma_W=0.153$)", m4_shared2 = "Buyout, shared shock $2c$ ($\\sigma_W=0.306$)",
  m4p_shared2 = "Buyout, $2c$ persistent ($\\rho_W=0.6$)", u_vc_shared = "VC, shared shock ($\\sigma_W=0.50$)",
  pc_V25_n20_2c = "Path-correlated payoffs, (X) fails (A$'$, $2c$)")
pc <- character(0)
for (d in names(DES)) {
  a <- mc[mc$design == d & mc$H == 12.5, ]; b <- mc[mc$design == d & mc$H == 15, ]
  stopifnot(nrow(a) == 1, nrow(b) == 1)
  pc <- c(pc, sprintf("%s & & %d & %s & %s & %s & %s & %s & %s & \\\\", DES[[d]], b$reps,
    rec("C", d, "reject.5.H12.5", a$reject.5, pct(a$reject.5)), rec("C", d, "reject.5.H15", b$reject.5, pct(b$reject.5)),
    rec("C", d, "mean.diff.H15", b$mean.diff, f3(b$mean.diff)), rec("C", d, "se.ratio.H15", b$se.ratio, f2(b$se.ratio)),
    rec("C", d, "median.corr.H15", b$median.corr, f2(b$median.corr)), rec("C", d, "tm.reject.5", b$tm.reject.5, pct(b$tm.reject.5))))
}
prov <- function(x) paste(unique(paste0(x$git.commit, if ("git.dirty" %in% names(x)) ifelse(x$git.dirty, " (uncommitted changes)", "") else "")), collapse = ", ")
