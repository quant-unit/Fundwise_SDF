  " & & $H_1$ & $\\hat\\beta_0$ & $\\hat\\beta_{H_1}$ & Diff. & SE & Corr. & $t_{\\mathrm{HI}}$ & $p$ \\\\", "\\midrule", pa,
  "\\midrule",
  "\\multicolumn{10}{@{}l}{\\textit{Panel B: two-moment test at $H=0$ (vintage mean pricing error and pair product), Preqin}} \\\\",
  " & & $V$ & Max.\\ $p$ & at $\\beta$ & \\multicolumn{2}{c}{95\\% set (hull)} & Share\\,\\% & & \\\\", "\\midrule", pb,
  "\\midrule",
