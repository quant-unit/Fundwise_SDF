  "Design & & Reps & $H_1=12.5$ & $H_1=15$ & Mean diff. & SE/SD & Corr. & Two-mom. & \\\\", "\\midrule")
tex <- c(tex, pc, "\\bottomrule", "\\end{tabular}%", "}", "\\par\\vspace{2pt}",
  paste0("{\\scriptsize\\textit{Notes:} Panel~A: $t_{\\mathrm{HI}}$ of Remark~\\ref{rem:horizon_invariance}; Diff.\\ $=\\hat\\beta_0-\\hat\\beta_{H_1}$, SE from the Bartlett estimator of the stacked vintage influence terms of both fits ",
